-- Таблица пользователей
CREATE TABLE IF NOT EXISTS USERS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMAIL VARCHAR(255) NOT NULL UNIQUE,
    PASSWORD VARCHAR(255) NOT NULL,
    FIRST_NAME VARCHAR(100),
    LAST_NAME VARCHAR(100),
    DISPLAY_NAME VARCHAR(255),
    ENABLED BOOLEAN DEFAULT TRUE,
    REGISTERED TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    STARTPOINT TIMESTAMP,
    ENDPOINT TIMESTAMP
);

-- Таблица ролей пользователей
CREATE TABLE IF NOT EXISTS USER_ROLE (
    USER_ID BIGINT NOT NULL,
    ROLE INTEGER NOT NULL,
    PRIMARY KEY (USER_ID, ROLE),
    FOREIGN KEY (USER_ID) REFERENCES USERS(ID) ON DELETE CASCADE
);

-- Таблица профилей
CREATE TABLE IF NOT EXISTS PROFILE (
    ID BIGINT PRIMARY KEY,
    LAST_FAILED_LOGIN TIMESTAMP,
    LAST_LOGIN TIMESTAMP,
    MAIL_NOTIFICATIONS INTEGER,
    FOREIGN KEY (ID) REFERENCES USERS(ID) ON DELETE CASCADE
);

-- Таблица контактов
CREATE TABLE IF NOT EXISTS CONTACT (
    ID BIGINT NOT NULL,
    CODE VARCHAR(50) NOT NULL,
    "VALUE" VARCHAR(255) NOT NULL,
    PRIMARY KEY (ID, CODE),
    FOREIGN KEY (ID) REFERENCES USERS(ID) ON DELETE CASCADE
);

-- Таблица проектов
CREATE TABLE IF NOT EXISTS PROJECT (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODE VARCHAR(50) NOT NULL UNIQUE,
    TITLE VARCHAR(255) NOT NULL,
    DESCRIPTION TEXT,
    TYPE_CODE VARCHAR(50) NOT NULL,
    PARENT_ID BIGINT,
    STARTPOINT TIMESTAMP,
    ENDPOINT TIMESTAMP,
    FOREIGN KEY (PARENT_ID) REFERENCES PROJECT(ID)
);

-- Таблица спринтов
CREATE TABLE IF NOT EXISTS SPRINT (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    STATUS_CODE VARCHAR(50) NOT NULL,
    STARTPOINT TIMESTAMP,
    ENDPOINT TIMESTAMP,
    CODE VARCHAR(50) NOT NULL,
    PROJECT_ID BIGINT NOT NULL,
    FOREIGN KEY (PROJECT_ID) REFERENCES PROJECT(ID) ON DELETE CASCADE,
    UNIQUE (PROJECT_ID, CODE)
);

-- Таблица задач
CREATE TABLE IF NOT EXISTS TASK (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITLE VARCHAR(255) NOT NULL,
    TYPE_CODE VARCHAR(50) NOT NULL,
    STATUS_CODE VARCHAR(50) NOT NULL,
    PROJECT_ID BIGINT NOT NULL,
    SPRINT_ID BIGINT,
    STARTPOINT TIMESTAMP,
    ENDPOINT TIMESTAMP DEFAULT NULL,
    PARENT_ID BIGINT DEFAULT NULL,
    FOREIGN KEY (PROJECT_ID) REFERENCES PROJECT(ID) ON DELETE CASCADE,
    FOREIGN KEY (SPRINT_ID) REFERENCES SPRINT(ID),
    FOREIGN KEY (PARENT_ID) REFERENCES TASK(ID)
);

-- Таблица активности
CREATE TABLE IF NOT EXISTS ACTIVITY (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AUTHOR_ID BIGINT NOT NULL,
    TASK_ID BIGINT NOT NULL,
    UPDATED TIMESTAMP NOT NULL,
    COMMENT TEXT,
    TITLE VARCHAR(255),
    DESCRIPTION TEXT,
    ESTIMATE INTEGER,
    TYPE_CODE VARCHAR(50),
    STATUS_CODE VARCHAR(50),
    PRIORITY_CODE VARCHAR(50),
    FOREIGN KEY (AUTHOR_ID) REFERENCES USERS(ID) ON DELETE CASCADE,
    FOREIGN KEY (TASK_ID) REFERENCES TASK(ID) ON DELETE CASCADE
);

-- Таблица принадлежности пользователей к задачам
CREATE TABLE IF NOT EXISTS USER_BELONG (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OBJECT_ID BIGINT NOT NULL,
    OBJECT_TYPE INTEGER NOT NULL,
    USER_ID BIGINT NOT NULL,
    USER_TYPE_CODE VARCHAR(50) NOT NULL,
    STARTPOINT TIMESTAMP,
    ENDPOINT TIMESTAMP,
    FOREIGN KEY (USER_ID) REFERENCES USERS(ID) ON DELETE CASCADE
);
-- Таблица reference (справочники)
CREATE TABLE IF NOT EXISTS REFERENCE (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODE VARCHAR(255) NOT NULL,
    TITLE VARCHAR(255),
    AUX VARCHAR(255),
    REF_TYPE VARCHAR(100),
    STARTPOINT TIMESTAMP,
    ENDPOINT TIMESTAMP,
    UNIQUE (REF_TYPE, CODE)
);
CREATE TABLE IF NOT EXISTS TASK_TAG (
    TASK_ID BIGINT NOT NULL,
    TAG VARCHAR(255) NOT NULL,
    PRIMARY KEY (TASK_ID, TAG),
    FOREIGN KEY (TASK_ID) REFERENCES TASK(ID) ON DELETE CASCADE
);