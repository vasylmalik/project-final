SET MODE PostgreSQL;

DROP TABLE IF EXISTS ACTIVITY;
DROP TABLE IF EXISTS ATTACHMENT;
DROP TABLE IF EXISTS CONTACT;
DROP TABLE IF EXISTS MAIL_CASE;
DROP TABLE IF EXISTS PROFILE;
DROP TABLE IF EXISTS PROJECT;
DROP TABLE IF EXISTS REFERENCE;
DROP TABLE IF EXISTS SPRINT;
DROP TABLE IF EXISTS TASK_TAG;
DROP TABLE IF EXISTS TASK;
DROP TABLE IF EXISTS USER_BELONG;
DROP TABLE IF EXISTS USER_ROLE;
DROP TABLE IF EXISTS USERS;

CREATE TABLE USERS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMAIL VARCHAR(255) NOT NULL UNIQUE,
    PASSWORD VARCHAR(255) NOT NULL,
    FIRST_NAME VARCHAR(255),
    LAST_NAME VARCHAR(255),
    DISPLAY_NAME VARCHAR(255) NOT NULL,
    STARTPOINT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE USER_ROLE (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID BIGINT NOT NULL,
    ROLE SMALLINT NOT NULL,
    CONSTRAINT UK_USER_ROLE UNIQUE (USER_ID, ROLE)
);

CREATE TABLE PROFILE (
    ID BIGINT PRIMARY KEY,
    LAST_LOGIN TIMESTAMP,
    LAST_FAILED_LOGIN TIMESTAMP,
    MAIL_NOTIFICATIONS BOOLEAN DEFAULT FALSE,
    CONSTRAINT FK_PROFILE_USER FOREIGN KEY (ID) REFERENCES USERS(ID) ON DELETE CASCADE
);

CREATE TABLE CONTACT (
    ID BIGINT NOT NULL,
    CODE VARCHAR(64) NOT NULL,
    VALUE VARCHAR(1024),
    PRIMARY KEY (ID, CODE),
    CONSTRAINT FK_CONTACT_PROFILE FOREIGN KEY (ID) REFERENCES PROFILE(ID) ON DELETE CASCADE
);

CREATE TABLE REFERENCE (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    STARTPOINT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ENDPOINT TIMESTAMP,
    TITLE VARCHAR(1024) NOT NULL,
    AUX VARCHAR,
    CODE VARCHAR(32) NOT NULL,
    REF_TYPE SMALLINT NOT NULL
);

